// Writes a zip the way the official yt-dlp zipapp is laid out: a `#!` line, then a zip whose offsets count from
// after it.
struct ZipBuilder {
  struct Entry {
    var name: String
    var data: Data
    var deflate = true
    // The Unix mode in the upper half of the external attributes (0o120777 is a symlink).
    var mode: UInt32 = 0o100644
  }

  var entries: [Entry] = []
  var prefix = Data("#!/usr/bin/env python3\n".utf8)

  mutating func add(_ name: String, _ text: String, deflate: Bool = true, mode: UInt32 = 0o100644) {
    entries.append(Entry(name: name, data: Data(text.utf8), deflate: deflate, mode: mode))
  }

  func build() -> Data {
    var zip = Data()
    var central = Data()
    for entry in entries {
      let name = Data(entry.name.utf8)
      let packed = entry.deflate ? Self.deflate(entry.data) : entry.data
      let crc = ZipExtractor.crc32(entry.data)
      let offset = UInt32(zip.count)
      zip.le32(0x0403_4b50)
      zip.le16(20)
      zip.le16(0x0800)
      zip.le16(entry.deflate ? 8 : 0)
      zip.le16(0)
      zip.le16(0x21)
      zip.le32(crc)
      zip.le32(UInt32(packed.count))
      zip.le32(UInt32(entry.data.count))
      zip.le16(UInt16(name.count))
      zip.le16(0)
      zip.append(name)
      zip.append(packed)

      central.le32(0x0201_4b50)
      central.le16(3 << 8 | 20)
      central.le16(20)
      central.le16(0x0800)
      central.le16(entry.deflate ? 8 : 0)
      central.le16(0)
      central.le16(0x21)
      central.le32(crc)
      central.le32(UInt32(packed.count))
      central.le32(UInt32(entry.data.count))
      central.le16(UInt16(name.count))
      central.le16(0)
      central.le16(0)
      central.le16(0)
      central.le16(0)
      central.le32(entry.mode << 16)
      central.le32(offset)
      central.append(name)
    }
    let centralOffset = UInt32(zip.count)
    zip.append(central)
    zip.le32(0x0605_4b50)
    zip.le16(0)
    zip.le16(0)
    zip.le16(UInt16(entries.count))
    zip.le16(UInt16(entries.count))
    zip.le32(UInt32(central.count))
    zip.le32(centralOffset)
    zip.le16(0)
    return prefix + zip
  }

  // A zipapp of the shape yt-dlp ships, small enough to build per test.
  static func zipapp(version: String, declaring declared: String? = nil) -> ZipBuilder {
    var zip = ZipBuilder()
    zip.add("__main__.py", "import yt_dlp\nyt_dlp.main()\n")
    zip.add("yt_dlp/__init__.py", "from .version import __version__\n")
    zip.add("yt_dlp/version.py", "# Autogenerated\n\n__version__ = '\(declared ?? version)'\n\nCHANNEL = 'stable'\n")
    zip.add("yt_dlp/extractor/__init__.py", "", deflate: false)
    zip.add("yt_dlp_ejs/__init__.py", "")
    zip.add("yt_dlp_ejs/yt/solver/core.min.js", String(repeating: "var a=1;", count: 200))
    return zip
  }

  private static func deflate(_ data: Data) -> Data {
    guard !data.isEmpty else { return Data([0x03, 0x00]) }
    let capacity = data.count + 1024
    var out = Data(count: capacity)
    let written = out.withUnsafeMutableBytes { dst in
      data.withUnsafeBytes { src in
        compression_encode_buffer(
          dst.bindMemory(to: UInt8.self).baseAddress!, capacity, src.bindMemory(to: UInt8.self).baseAddress!,
          data.count, nil, COMPRESSION_ZLIB)
      }
    }
    precondition(written > 0)
    return out.prefix(written)
  }
}

extension Data {
  mutating func le16(_ value: UInt16) { Swift.withUnsafeBytes(of: value.littleEndian) { append(contentsOf: $0) } }
  mutating func le32(_ value: UInt32) { Swift.withUnsafeBytes(of: value.littleEndian) { append(contentsOf: $0) } }

  var sha256Hex: String { SHA256.hash(data: self).map { String(format: "%02x", $0) }.joined() }
}

// Serves canned responses to a URLSession built with `StubProtocol.session()`. One stub at a time: tests in a class
// run one after another.
final class StubProtocol: URLProtocol, @unchecked Sendable {
  typealias Handler = @Sendable (URLRequest) async throws -> (Int, Data)

  private static let lock = NSLock()
  nonisolated(unsafe) private static var handler: Handler?
  nonisolated(unsafe) private static var seen: [URL] = []
  nonisolated(unsafe) private static var redirects: [String: URL] = [:]

  // `redirects` answers those URLs with a 302 to the given one, the way github.com hands an asset to its CDN.
  static func serve(redirects: [String: URL] = [:], _ handler: @escaping Handler) {
    lock.withLock {
      self.handler = handler
      self.redirects = redirects
      seen = []
    }
  }

  static var requests: [URL] { lock.withLock { seen } }

  static func session() -> URLSession {
    let config = URLSessionConfiguration.ephemeral
    config.protocolClasses = [StubProtocol.self]
    return URLSession(configuration: config)
  }

  private var work: Task<Void, Never>?

  override class func canInit(with request: URLRequest) -> Bool { true }
  override class func canonicalRequest(for request: URLRequest) -> URLRequest { request }

  override func startLoading() {
    let request = self.request
    let (handler, client, redirect) = Self.lock.withLock { () -> (Handler?, URLProtocolClient?, URL?) in
      if let url = request.url { Self.seen.append(url) }
      return (Self.handler, self.client, request.url.flatMap { Self.redirects[$0.absoluteString] })
    }
    if let redirect, let url = request.url {
      let response = HTTPURLResponse(
        url: url, statusCode: 302, httpVersion: "HTTP/1.1", headerFields: ["Location": redirect.absoluteString])!
      client?.urlProtocol(self, wasRedirectedTo: URLRequest(url: redirect), redirectResponse: response)
      return
    }
    work = Task { [self] in
      do {
        guard let handler else { throw URLError(.unsupportedURL) }
        let (status, body) = try await handler(request)
        guard !Task.isCancelled else { return }
        let response = HTTPURLResponse(url: request.url!, statusCode: status, httpVersion: "HTTP/1.1", headerFields: nil)!
        client?.urlProtocol(self, didReceive: response, cacheStoragePolicy: .notAllowed)
        client?.urlProtocol(self, didLoad: body)
        client?.urlProtocolDidFinishLoading(self)
      } catch {
        client?.urlProtocol(self, didFailWithError: error)
      }
    }
  }

  override func stopLoading() {
    work?.cancel()
  }
}

// A fake GitHub release: the JSON, the zipapp and its SHA2-256SUMS.
struct FakeRelease {
  var tag: String
  var zipapp: Data
  var sums: String?
  // The real release's shape; the stub answers every request, so nothing reaches GitHub.
  var assetUrl: String
  var sumsUrl: String

  init(_ tag: String, zipapp: Data? = nil, sums: String? = nil) {
    self.tag = tag
    assetUrl = "https://github.com/yt-dlp/yt-dlp/releases/download/\(tag)/yt-dlp"
    sumsUrl = "https://github.com/yt-dlp/yt-dlp/releases/download/\(tag)/SHA2-256SUMS"
    let app = zipapp ?? ZipBuilder.zipapp(version: tag).build()
    self.zipapp = app
    self.sums = sums
  }

  static let api = YtDlpUpdater.latestRelease

  var json: Data {
    let body: [String: Any] = [
      "tag_name": tag,
      "assets": [
        ["name": "yt-dlp.exe", "browser_download_url": "https://github.com/yt-dlp/yt-dlp/releases/download/\(tag)/yt-dlp.exe"],
        ["name": "yt-dlp", "browser_download_url": assetUrl],
        ["name": "SHA2-256SUMS", "browser_download_url": sumsUrl],
      ],
    ]
    return try! JSONSerialization.data(withJSONObject: body)
  }

  var sumsText: String {
    sums ?? "\(Data("exe".utf8).sha256Hex)  yt-dlp.exe\n\(zipapp.sha256Hex)  yt-dlp\n"
  }

  // The JSON at the API URL, the sums at any URL named SHA2-256SUMS, the zipapp at any other (a CDN it was
  // redirected to included). `hold` runs before the zipapp is served, `delay` before every answer.
  func handler(
    delay: TimeInterval = 0, hold: @escaping @Sendable () async -> Void = {}
  ) -> StubProtocol.Handler {
    let json = self.json
    let sums = Data(sumsText.utf8)
    let app = zipapp
    return { request in
      if delay > 0 { try? await Task.sleep(nanoseconds: UInt64(delay * 1e9)) }
      if request.url == FakeRelease.api { return (200, json) }
      if request.url?.lastPathComponent == "SHA2-256SUMS" { return (200, sums) }
      await hold()
      return (200, app)
    }
  }
}
